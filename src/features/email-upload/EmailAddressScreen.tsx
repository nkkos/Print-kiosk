import { KioskScreenLayout } from '../../layouts/KioskScreenLayout/KioskScreenLayout';
import { ArrowRight, Mail, MailOpen, Paperclip, Send, ShieldCheck } from 'lucide-react';
import { Button } from '../../components/Button/Button';
import { StepList } from '../../components/StepList/StepList';
import { acceptedFormatsLabel, MAX_FILE_SIZE_MB } from '../../utils/fileLimits';
import { useTranslation } from '../../i18n';
import type { Language } from '../../i18n';
import type { EndSessionReason, PrintOrder } from '../../types/kiosk';
import styles from './EmailAddressScreen.module.css';

// First Email upload screen — see docs/email-upload-requirements.md.
// Prototype simplification: `emailAddress` is a static placeholder string
// computed by the caller (App.tsx), not generated by a real catch-all
// domain + inbound webhook backend yet. The accepted-format list is a
// plausible placeholder, not a confirmed final list.
interface EmailAddressScreenProps {
  emailAddress: string;
  onNext: () => void;
  onBack: () => void;
  onHome: () => void;
  onEndSession: (reason: EndSessionReason) => void;
  /** Current Cart contents, shown in the btn-cart popup. */
  cartItems: PrintOrder[];
  /** Adjusts a Cart item's quantity (docs/cart-requirements.md). */
  onQuantityChange: (id: string, quantity: number) => void;
  /** Removes a Cart item entirely (docs/cart-requirements.md). */
  onRemoveItem: (id: string) => void;
  /** Navigates to the Payment Status screen with the checked Cart items. */
  onProceedToPayment: (selectedItems: PrintOrder[]) => void;
  isConnectionLost: boolean;
  onSimulateConnectionLost: () => void;
  onSimulateConnectionRestored: () => void;
  onLogin: (email: string, password: string) => Promise<void>;
  accountId: string | null;
  /** Navigates to the Personal Account screen (docs/personal-account-requirements.md)
   * — used by the footer's btn-account. */
  onGoToPersonalAccount: () => void;
  hasPendingPaidOrders: boolean;
  onDismissPaidOrdersPrompt: () => void;
  onGoToPaidOrders: () => void;
  onLanguageChange: (language: Language) => void;
}

export function EmailAddressScreen({
  emailAddress,
  onNext,
  onBack,
  onHome,
  onEndSession,
  cartItems,
  onQuantityChange,
  onRemoveItem,
  onProceedToPayment,
  isConnectionLost,
  onSimulateConnectionLost,
  onSimulateConnectionRestored,
  onLogin,
  accountId,
  onGoToPersonalAccount,
  hasPendingPaidOrders,
  onDismissPaidOrdersPrompt,
  onGoToPaidOrders,
  onLanguageChange,
}: EmailAddressScreenProps) {
  const t = useTranslation();
  return (
    <KioskScreenLayout
      onEndSession={onEndSession}
      onBack={onBack}
      onHome={onHome}
      cartItems={cartItems}
      onQuantityChange={onQuantityChange}
      onRemoveItem={onRemoveItem}
      onProceedToPayment={onProceedToPayment}
      isConnectionLost={isConnectionLost}
      onSimulateConnectionLost={onSimulateConnectionLost}
      onSimulateConnectionRestored={onSimulateConnectionRestored}
      onLogin={onLogin}
      accountId={accountId}
      onGoToPersonalAccount={onGoToPersonalAccount}
      hasPendingPaidOrders={hasPendingPaidOrders}
      onDismissPaidOrdersPrompt={onDismissPaidOrdersPrompt}
      onGoToPaidOrders={onGoToPaidOrders}
      onLanguageChange={onLanguageChange}
    >
      <div className={styles.intro}>
        <h1 className={styles.title}>{t.emailAddress.title}</h1>
        <p className={styles.subtitle}>{t.emailAddress.subtitle}</p>
      </div>

      <div className={styles.body}>
        <StepList
          id="email-steps"
          steps={[
            {
              icon: <MailOpen size={48} strokeWidth={1.5} />,
              title: t.emailAddress.step1Title,
              text: t.emailAddress.step1Text,
            },
            {
              icon: <Paperclip size={48} strokeWidth={1.5} />,
              title: t.emailAddress.step2Title,
              text: t.emailAddress.step2Text,
            },
            {
              icon: <Send size={48} strokeWidth={1.5} />,
              title: t.emailAddress.step3Title,
              text: t.emailAddress.step3Text,
            },
          ]}
        />

        <aside className={styles.addressCard}>
          <p className={styles.sendTo}>
            <Mail size={30} strokeWidth={1.75} aria-hidden="true" />
            {t.emailAddress.sendTo}
          </p>
          {/* The one thing to copy — big, unbroken, in its own box. */}
          <p className={styles.address} id="email-address-value">
            {emailAddress}
          </p>
          <p className={styles.sessionOnly}>
            <ShieldCheck size={24} strokeWidth={2} aria-hidden="true" />
            {t.emailAddress.sessionOnly}
          </p>
          <p className={styles.formats}>
            {t.uploadMethodSelection.formatsHint(acceptedFormatsLabel(), MAX_FILE_SIZE_MB)}
          </p>
          {/* "Next" (docs/email-upload-requirements.md, step 3): pressed once
              the e-mail is sent; the next screen waits for it. */}
          <Button
            id="email-address-next"
            variant="primary"
            label={t.emailAddress.sent}
            trailingIcon={<ArrowRight size={26} strokeWidth={2.25} />}
            onClick={onNext}
          />
        </aside>
      </div>
    </KioskScreenLayout>
  );
}
